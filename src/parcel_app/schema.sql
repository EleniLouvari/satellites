CREATE TABLE IF NOT EXISTS public.app_sessions (
 token_hash text PRIMARY KEY, app_user_id bigint NOT NULL REFERENCES public.app_users(app_user_id),
 csrf_token text NOT NULL, expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS app_sessions_expiry ON public.app_sessions(expires_at);
CREATE TABLE IF NOT EXISTS public.auth_attempts (
 bucket_key text PRIMARY KEY, window_start timestamptz NOT NULL, attempts integer NOT NULL
);
CREATE TABLE IF NOT EXISTS public.parcel_uploads (
 upload_id uuid PRIMARY KEY, app_user_id bigint NOT NULL REFERENCES public.app_users(app_user_id),
 filename text NOT NULL, storage_path text NOT NULL, sha256 text NOT NULL, size_bytes bigint NOT NULL,
 status text NOT NULL, metadata jsonb NOT NULL DEFAULT '{}', error text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.analysis_runs (
 run_id uuid PRIMARY KEY, app_user_id bigint NOT NULL REFERENCES public.app_users(app_user_id),
 name text NOT NULL, upload_id uuid NOT NULL REFERENCES public.parcel_uploads(upload_id), layer text,
 parcel_id_field text NOT NULL, partition_field text, processing jsonb NOT NULL, account_ids jsonb NOT NULL,
 revision integer NOT NULL DEFAULT 1, validated_revision integer, status text NOT NULL DEFAULT 'draft',
 summary jsonb NOT NULL DEFAULT '{}', config jsonb NOT NULL DEFAULT '{}', output_dir text NOT NULL,
 error text, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.run_accounts (
 run_id uuid NOT NULL REFERENCES public.analysis_runs(run_id),
 eo_user_id bigint NOT NULL REFERENCES public.eo_users(eo_user_id), position integer NOT NULL, username text NOT NULL,
 PRIMARY KEY(run_id,eo_user_id), UNIQUE(run_id,position)
);
ALTER TABLE public.analysis_runs ADD COLUMN IF NOT EXISTS scheduling text NOT NULL DEFAULT 'batches';
ALTER TABLE public.analysis_runs ADD COLUMN IF NOT EXISTS deletion_manifest jsonb;
CREATE TABLE IF NOT EXISTS public.run_events (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id uuid NOT NULL REFERENCES public.analysis_runs(run_id), stage text NOT NULL,
 level text NOT NULL DEFAULT 'INFO', message text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS run_events_run ON public.run_events(run_id,event_id);
CREATE TABLE IF NOT EXISTS public.run_artifacts (
 artifact_id uuid PRIMARY KEY, run_id uuid NOT NULL REFERENCES public.analysis_runs(run_id), kind text NOT NULL,
 name text NOT NULL, storage_path text NOT NULL, size_bytes bigint NOT NULL, sha256 text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(run_id,kind,name)
);
CREATE TABLE IF NOT EXISTS public.web_jobs (
 job_id uuid PRIMARY KEY, app_user_id bigint NOT NULL REFERENCES public.app_users(app_user_id),
 kind text NOT NULL, target_id text NOT NULL, payload jsonb NOT NULL DEFAULT '{}', status text NOT NULL DEFAULT 'pending',
 claim_token uuid, heartbeat_at timestamptz, error text,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS web_jobs_active_target ON public.web_jobs(kind,target_id) WHERE status IN ('pending','running');
CREATE INDEX IF NOT EXISTS web_jobs_queue ON public.web_jobs(status,created_at);
CREATE TABLE IF NOT EXISTS public.eda_runs (
 eda_id uuid PRIMARY KEY, run_id uuid NOT NULL REFERENCES public.analysis_runs(run_id),
 app_user_id bigint NOT NULL REFERENCES public.app_users(app_user_id), selected_columns jsonb NOT NULL,
 config jsonb NOT NULL, input_sha256 text NOT NULL, output_dir text NOT NULL,
 status text NOT NULL DEFAULT 'queued', artifacts jsonb NOT NULL DEFAULT '[]', error text,
 created_at timestamptz NOT NULL DEFAULT now(), started_at timestamptz, finished_at timestamptz
);
CREATE INDEX IF NOT EXISTS eda_runs_owner_run ON public.eda_runs(app_user_id,run_id,created_at);
