-- Legacy manually-created integer primary keys may have neither identity nor a default.
-- Lock against concurrent inserts while assigning a fresh sequence above existing IDs.
DO $$
DECLARE entry record; sequence_name text; largest bigint;
BEGIN
 FOR entry IN SELECT * FROM (VALUES ('app_users','app_user_id'),('eo_users','eo_user_id')) AS ids(tbl,col)
 LOOP
  EXECUTE format('LOCK TABLE public.%I IN ACCESS EXCLUSIVE MODE',entry.tbl);
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name=entry.tbl
             AND column_name=entry.col AND is_identity='NO' AND column_default IS NULL) THEN
   sequence_name := entry.tbl || '_web_id_seq';
   EXECUTE format('CREATE SEQUENCE IF NOT EXISTS public.%I',sequence_name);
   EXECUTE format('SELECT COALESCE(max(%I),0) FROM public.%I',entry.col,entry.tbl) INTO largest;
   PERFORM setval(('public.' || sequence_name)::regclass, GREATEST(largest,1), largest > 0);
   EXECUTE format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I',sequence_name,entry.tbl,entry.col);
   EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I SET DEFAULT nextval(%L::regclass)',
                  entry.tbl,entry.col,'public.' || sequence_name);
  END IF;
 END LOOP;
END $$;
